// Writes src/kit/icon-data.js: the icons gs.icons can draw, taken from the Game Icons set
// (game-icons.net, CC BY 3.0, by Lorc, Delapouite and contributors) as packed by Iconify.
// Usage: node scripts/icons/build.mjs          (after npm install; the set is a dev dependency)
// To add or drop an icon, edit scripts/icons/names.json (names as on game-icons.net) and run it again.
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

const here = new URL('.', import.meta.url), require = createRequire(import.meta.url);
const set = require('@iconify-json/game-icons/icons.json');
const { icons, alias } = JSON.parse(readFileSync(new URL('names.json', here), 'utf8'));
if (set.width !== 512 || set.height !== 512) throw new Error('the set is no longer on a 512 grid: src/kit/icons.js expects one');

const out = {}, problems = [];
for (const name of [...new Set(icons)].sort()) {
  const body = set.icons[name]?.body;
  const d = body && /^<path fill="currentColor" d="([^"]+)"\/>$/.exec(body)?.[1];
  if (!d) problems.push(body ? `${name}: not a single path` : `${name}: not in the set`); else out[name] = d;
}
for (const [word, name] of Object.entries(alias)) {
  if (!out[name]) problems.push(`alias ${word}: there is no icon called ${name}`);
  if (out[word] && word !== name) problems.push(`alias ${word} is also an icon's own name`);
}
if (problems.length) { console.error(problems.join('\n')); process.exit(1); }
const plain = Object.fromEntries(Object.entries(alias).filter(([word, name]) => word !== name));

const js = `// The icons gs.icons draws: ${Object.keys(out).length} of the Game Icons (game-icons.net) by Lorc, Delapouite and contributors,
// CC BY 3.0, each one SVG path on a 512 grid. Generated by scripts/icons/build.mjs from scripts/icons/names.json;
// don't edit by hand.
export const ICONS = ${JSON.stringify(out, null, 0).replace(/","/g, '",\n"').replace(/^\{/, '{\n').replace(/\}$/, '\n}')};
// plain words for the icons most games want: icon(c, 'sword') is the broadsword
export const ALIAS = ${JSON.stringify(plain)};
`;
writeFileSync(new URL('../../src/kit/icon-data.js', here), js);
console.log(`${Object.keys(out).length} icons and ${Object.keys(plain).length} plain words, ${(js.length / 1024).toFixed(0)} KB`);
