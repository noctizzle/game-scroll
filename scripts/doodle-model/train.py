import os, sys, numpy as np, torch, torch.nn as nn, torch.nn.functional as F, json, time
torch.manual_seed(1); np.random.seed(1); torch.set_num_threads(4)
DIR = sys.argv[1] if len(sys.argv) > 1 else 'qd-data'
CLASSES = json.load(open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'classes.json')))
X=[];Y=[]
for i,c in enumerate(CLASSES):
    a=np.load(os.path.join(DIR, c.replace(' ','_') + '.npy'))[:12000]; X.append(a); Y.append(np.full(len(a),i))
X=np.concatenate(X).reshape(-1,1,28,28).astype(np.float32)/255; Y=np.concatenate(Y)
p=np.random.permutation(len(X)); X=X[p]; Y=Y[p]
nt=len(X)//12; Xte,Yte=torch.tensor(X[:nt]),torch.tensor(Y[:nt]); Xtr,Ytr=torch.tensor(X[nt:]),torch.tensor(Y[nt:])
class Net(nn.Module):
    def __init__(s,n):
        super().__init__(); s.c1=nn.Conv2d(1,16,3,padding=1); s.c2=nn.Conv2d(16,32,3,padding=1); s.c3=nn.Conv2d(32,64,3,padding=1); s.f1=nn.Linear(64*3*3,128); s.f2=nn.Linear(128,n)
    def forward(s,x):
        x=F.max_pool2d(F.relu(s.c1(x)),2); x=F.max_pool2d(F.relu(s.c2(x)),2); x=F.max_pool2d(F.relu(s.c3(x)),2)
        return s.f2(F.relu(s.f1(x.flatten(1))))
m=Net(len(CLASSES)); opt=torch.optim.Adam(m.parameters(),2e-3)
def aug(x):
    b=x.shape[0]; ang=(torch.rand(b)-.5)*0.35; sc=1/(0.8+torch.rand(b)*0.35); tx=(torch.rand(b)-.5)*0.25; ty=(torch.rand(b)-.5)*0.25
    th=torch.stack([torch.stack([sc*torch.cos(ang),-sc*torch.sin(ang),tx],1),torch.stack([sc*torch.sin(ang),sc*torch.cos(ang),ty],1)],1)
    g=F.affine_grid(th,x.shape,align_corners=False); return F.grid_sample(x,g,align_corners=False)
E=6; steps=E*(len(Xtr)//256); sched=torch.optim.lr_scheduler.OneCycleLR(opt,3e-3,total_steps=steps)
for ep in range(E):
    t=time.time(); m.train(); perm=torch.randperm(len(Xtr))
    for i in range(0,len(Xtr)-255,256):
        idx=perm[i:i+256]; x=Xtr[idx]
        if ep < E-1: x=aug(x)
        loss=F.cross_entropy(m(x),Ytr[idx]); opt.zero_grad(); loss.backward(); opt.step(); sched.step()
    m.eval()
    with torch.no_grad(): acc=(m(Xte).argmax(1)==Yte).float().mean().item()
    print(f"epoch {ep} loss {loss.item():.3f} test {acc:.3f} {time.time()-t:.0f}s",flush=True)
torch.save(m.state_dict(),DIR + '/model.pt')
# export int8 per tensor
out={'classes':CLASSES,'layers':[]}
blob=bytearray()
for k,v in m.state_dict().items():
    a=v.numpy().astype(np.float32).ravel(); s=float(np.abs(a).max()/127) or 1e-6
    q=np.clip(np.round(a/s),-127,127).astype(np.int8)
    out['layers'].append({'name':k,'shape':list(v.shape),'scale':s,'offset':len(blob)}); blob+=q.tobytes()
open(DIR + '/doodle.bin','wb').write(bytes(blob)); json.dump(out,open(DIR + '/doodle.json','w'))
# check quantized accuracy
with torch.no_grad():
    sd=m.state_dict()
    for L in out['layers']:
        q=np.frombuffer(bytes(blob[L['offset']:L['offset']+int(np.prod(L['shape']))]),dtype=np.int8).astype(np.float32)*L['scale']
        sd[L['name']]=torch.tensor(q.reshape(L['shape']))
    m.load_state_dict(sd); acc=(m(Xte).argmax(1)==Yte).float().mean().item()
    np.save(DIR + '/test_x.npy', Xte[:200].numpy()); np.save(DIR + '/test_y.npy', Yte[:200].numpy())
    np.save(DIR + '/test_logits.npy', m(Xte[:200]).numpy())
print('int8 test', acc, 'bytes', len(blob))
